// Downloads the full ATR sheet (Tournament ELO + TRDB) and packs it into
// src/server/core/snapshot.ts, so the "load sample data" mod action can load the
// complete ranking before Reddit approves fetching docs.google.com.
// Usage: npm run snapshot
import { writeFileSync } from 'node:fs';
import { gzipSync } from 'node:zlib';

const SHEET_ID = '12CKvt3uO1NWBL3DsBN0adcynPUcuOIpCkobvgtymJq8';
const url = (tab) =>
  `https://docs.google.com/spreadsheets/d/${SHEET_ID}/gviz/tq?tqx=out:csv&sheet=${encodeURIComponent(tab)}`;

async function download(tab) {
  const res = await fetch(url(tab));
  if (!res.ok) throw new Error(`HTTP ${res.status} for tab "${tab}"`);
  const text = await res.text();
  if (text.trimStart().startsWith('<')) throw new Error(`Tab "${tab}" came back as a web page. Is the sheet public?`);
  return text;
}

const [elo, trdb] = await Promise.all([download('🏆 Tournament ELO'), download('🗄️TRDB')]);
const packed = gzipSync(Buffer.from(JSON.stringify({ elo, trdb }), 'utf8'), { level: 9 }).toString('base64');
const date = new Date().toISOString().slice(0, 10);

writeFileSync(
  new URL('../src/server/core/snapshot.ts', import.meta.url),
  `// Generated by scripts/update-snapshot.mjs on ${date}. Do not edit by hand.\n` +
    `export const SNAPSHOT_DATE: string = '${date}';\n` +
    `export const SNAPSHOT_GZIP_BASE64: string =\n  '${packed}';\n`
);
console.log(
  `Snapshot saved: ${elo.split('\n').length} Elo rows, ${trdb.split('\n').length} TRDB rows, ${Math.round(packed.length / 1024)} KB packed.`
);
